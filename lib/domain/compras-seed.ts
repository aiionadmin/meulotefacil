export function contadoresItens(itens: { quantidade: number; quantidadeCotada: number; quantidadeComprada: number; quantidadeRecebida: number }[]) {
  const q = itens.reduce((a, i) => a + i.quantidade, 0);
  return {
    cotados: `${itens.reduce((a, i) => a + Math.min(i.quantidadeCotada, i.quantidade), 0)} de ${q}`,
    comprados: `${itens.reduce((a, i) => a + Math.min(i.quantidadeComprada, i.quantidade), 0)} de ${q}`,
    recebidos: `${itens.reduce((a, i) => a + Math.min(i.quantidadeRecebida, i.quantidade), 0)} de ${q}`,
  };
}
